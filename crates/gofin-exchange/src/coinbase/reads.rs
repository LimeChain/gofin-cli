    pub(super) fn path(
        self,
        parameters: &[String],
        query: &CoinbaseQuery,
    ) -> Result<String, CoinbaseError> {
        let d = self.descriptor();
        if parameters.len() != d.parameters.len() {
            return Err(CoinbaseError::InvalidRequest);
        }
        let mut path = d.path.to_owned();
        for (key, value) in d.parameters.iter().zip(parameters) {
            if value.is_empty() || value.len() > 256 || value.chars().any(char::is_control) {
                return Err(CoinbaseError::InvalidRequest);
            }
            path = path.replace(&format!("{{{key}}}"), &segment(value));
        }
        query_path(&path, query, d.query)
    }
